# -------------------------------------------------------
# 메인
# -------------------------------------------------------
def run(input_file=INPUT_FILE):
    df = pd.read_csv(input_file)
    df = df.drop_duplicates(subset=['논문ID'])
    print(f"총 고유 논문 수: {len(df):,}건\n")

    # 검색용 텍스트 생성 (제목 + 키워드 + 초록, 소문자)
    df['search_text'] = (
        df['제목'].fillna('') + ' ' +
        df['키워드'].fillna('') + ' ' +
        df['초록'].fillna('')
    ).str.lower()

    # 카테고리별 논문 수 카운팅
    cat_masks = {}
    for cat, keywords in CATEGORIES.items():
        pattern = '|'.join(keywords)
        cat_masks[cat] = df['search_text'].str.contains(pattern, na=False)

    # 결과 출력 (논문 수 내림차순)
    print("=" * 45)
    print(f"{'카테고리':<22} {'논문 수':>8}  {'비율':>6}")
    print("=" * 45)
    counts = {cat: mask.sum() for cat, mask in cat_masks.items()}
    for cat, count in sorted(counts.items(), key=lambda x: -x[1]):
        ratio = count / len(df) * 100
        print(f"{cat:<22} {count:>8,}  {ratio:>5.1f}%")

    # 중복 분석 (한 논문이 몇 개 카테고리에 해당하는지)
    df['cat_count'] = sum(mask.astype(int) for mask in cat_masks.values())

    print("\n" + "=" * 45)
    print("복수 카테고리 해당 논문 분포")
    print("=" * 45)
    for n, cnt in df['cat_count'].value_counts().sort_index().items():
        bar = '█' * min(cnt // 20, 30)
        print(f"  {n}개 카테고리: {cnt:>5,}건  {bar}")

    no_cat_count = (df['cat_count'] == 0).sum()
    print(f"\n  ※ 어느 카테고리도 미해당: {no_cat_count:,}건")

    # CSV 저장
    result_df = pd.DataFrame([
        {'카테고리': cat, '논문수': count, '비율(%)': round(count / len(df) * 100, 1)}
        for cat, count in sorted(counts.items(), key=lambda x: -x[1])
    ])
    result_df.to_csv('카테고리_볼륨_확인결과.csv', index=False, encoding='utf-8-sig')
    print("\n✅ 결과 저장: 카테고리_볼륨_확인결과.csv")


if __name__ == '__main__':
    run()