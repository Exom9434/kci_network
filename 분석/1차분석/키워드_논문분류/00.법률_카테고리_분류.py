"""
법률 카테고리 분류 스크립트
============================
- 00.전체_법률_목록(2026.03.20).csv 의 결합_이름 칼럼을 바탕으로
  각 법률에 카테고리를 부여한다.

카테고리 목록:
    공법, 민사법, 형사법, 데이터법, 지식재산권법,
    노동법, 사회보장법, 경제법, 금융법, 조세법, 의료법, 기타

분류 기준:
    1. 법령분야코드의 앞 2자리(편 번호)로 1차 매핑
    2. 편 내부에서 결합_이름 키워드로 예외 처리
       - 17편 문화·공보  : "제2절 저작권" → 지식재산권법 (나머지 기타)
       - 19편 재정·경제일반: "물가·공정거래|외자도입|민간투자" → 경제법 (나머지 공법)
       - 43편 정보통신    : "제3장 정보통신" → 데이터법
                           "체신금융"       → 금융법
                           나머지           → 기타
"""

import pandas as pd

INPUT_CSV  = '00.전체_법률_목록(2026.03.20).csv'
OUTPUT_CSV = '00.전체_법률_목록(2026.03.20).csv'   # 원본에 덮어쓰기

# ── 데이터 로드 ───────────────────────────────────────
df = pd.read_csv(INPUT_CSV, encoding='utf-8-sig')
df['편_코드'] = df['법령분야코드'].astype(str).str.zfill(8).str[0:2]

# ── 1단계: 편 기본 매핑 ───────────────────────────────
편_매핑 = {
    # 공법
    '01': '공법', '02': '공법', '03': '공법', '04': '공법',
    '05': '공법', '06': '공법', '07': '공법', '10': '공법',
    '11': '공법', '12': '공법', '13': '공법', '14': '공법',
    '44': '공법',
    # 민사법
    '08': '민사법',
    # 형사법
    '09': '형사법',
    # 사회보장법
    '15': '사회보장법', '38': '사회보장법',
    # 금융법
    '23': '금융법',
    # 조세법
    '20': '조세법', '21': '조세법',
    # 의료법
    '36': '의료법', '37': '의료법',
    # 노동법
    '40': '노동법',
    # 지식재산권법
    '30': '지식재산권법',
    # 경제법
    '28': '경제법',
    # 기타 (교육·농업·환경·건설·에너지·해운·교통 등)
    '16': '기타', '17': '기타', '18': '기타', '19': '기타',
    '22': '기타', '24': '기타', '25': '기타', '26': '기타',
    '27': '기타', '29': '기타', '31': '기타', '32': '기타',
    '33': '기타', '34': '기타', '35': '기타', '39': '기타',
    '41': '기타', '42': '기타', '43': '기타',
}

df['카테고리'] = df['편_코드'].map(편_매핑)

# ── 2단계: 편 내부 예외 처리 ─────────────────────────

# 17편: "제2절 저작권"만 지식재산권법, 나머지는 기타 유지
mask_저작권 = (df['편_코드'] == '17') & df['결합_이름'].str.contains('제2절 저작권', na=False)
df.loc[mask_저작권, '카테고리'] = '지식재산권법'

# 19편: 기본값 공법으로 재설정 후, 경제 관련 분야만 경제법으로 변경
df.loc[df['편_코드'] == '19', '카테고리'] = '공법'
mask_19_경제 = (df['편_코드'] == '19') & \
               df['결합_이름'].str.contains('물가·공정거래|외자도입|민간투자', na=False)
df.loc[mask_19_경제, '카테고리'] = '경제법'

# 43편: 정보통신 → 데이터법 / 체신금융 → 금융법 / 나머지(우정·전파) → 기타
mask_43_데이터 = (df['편_코드'] == '43') & df['결합_이름'].str.contains('제3장 정보통신', na=False)
df.loc[mask_43_데이터, '카테고리'] = '데이터법'
mask_43_금융  = (df['편_코드'] == '43') & df['결합_이름'].str.contains('체신금융', na=False)
df.loc[mask_43_금융, '카테고리'] = '금융법'

# ── 결과 출력 ─────────────────────────────────────────
print('=== 카테고리 분포 ===')
counts = df['카테고리'].value_counts()
for cat, n in counts.items():
    print(f'  {cat:<12} {n:4d}개')
print(f'  {"합계":<12} {counts.sum():4d}개')
print(f'\n미분류(NaN): {df["카테고리"].isna().sum()}개')

# ── 저장 ─────────────────────────────────────────────
df.drop(columns=['편_코드']).to_csv(OUTPUT_CSV, index=False, encoding='utf-8-sig')
print(f'\n저장 완료 → {OUTPUT_CSV}')
